#!/usr/bin/env python3
"""Generate tools/webui-sim/public/js/tz-posix.js: IANA zone -> POSIX TZ rule.

The hub has no zoneinfo database, so the web UI ships this table and sends
the chosen zone's POSIX rule (e.g. "EST5EDT,M3.2.0,M11.1.0") to the hub.
Rules come from the footer line of each TZif v2+ file, which is the rule
tzcode itself uses for times after the last explicit transition.

Usage: python3 tools/gen_tz_posix.py [ZONEINFO_DIR]   (default /usr/share/zoneinfo)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "tools" / "webui-sim" / "public" / "js" / "tz-posix.js"


def footer_rule(path):
    data = path.read_bytes()
    if data[:4] != b"TZif" or data[4:5] not in (b"2", b"3", b"4"):
        raise ValueError(f"{path}: not a TZif v2+ file")
    if not data.endswith(b"\n"):
        raise ValueError(f"{path}: missing footer")
    rule = data[data.rindex(b"\n", 0, len(data) - 1) + 1:-1].decode("ascii")
    if not rule:
        raise ValueError(f"{path}: empty footer rule")
    return rule


def main():
    zoneinfo = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo")
    zones = {"UTC"}
    for line in (zoneinfo / "zone.tab").read_text().splitlines():
        if line and not line.startswith("#"):
            zones.add(line.split("\t")[2])
    table = {zone: footer_rule(zoneinfo / zone) for zone in sorted(zones)}
    # Browsers may report a legacy name (Asia/Calcutta, Europe/Kiev); map
    # every alias file that is byte-identical to a canonical zone.
    canonical = {(zoneinfo / z).read_bytes(): z for z in sorted(zones)}
    aliases = {}
    for path in sorted(zoneinfo.rglob("*")):
        name = path.relative_to(zoneinfo).as_posix()
        if (not path.is_file() or name in zones or name.split("/")[0] in ("posix", "right")
                or "." in name or name[0].islower()):
            continue
        target = canonical.get(path.read_bytes())
        if target:
            aliases[name] = target
    version = (zoneinfo / "+VERSION").read_text().strip() if (zoneinfo / "+VERSION").exists() else "unknown"
    alias_body = ",\n".join(f"  {json.dumps(a)}: {json.dumps(z)}" for a, z in aliases.items())
    body = ",\n".join(f"  {json.dumps(z)}: {json.dumps(r)}" for z, r in table.items())
    OUT.write_text(
        "/* Generated by tools/gen_tz_posix.py from the tz database"
        f" ({version}); do not edit.\n"
        "   IANA zone -> POSIX TZ rule, for the hub's offline time zone. */\n"
        f"export const TZ_POSIX = {{\n{body}\n}};\n"
        "\n/* legacy or alternate name -> canonical zone */\n"
        f"export const TZ_ALIASES = {{\n{alias_body}\n}};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(table)} zones, {len(aliases)} aliases")


if __name__ == "__main__":
    main()
